from mockymock.debug.gdb_session import ResultRecord
from mockymock.debug.variable_map import (
    declared_data_names,
    parse_local_header,
    read_variable,
    unavailable_names,
)

# Verbatim from a real `cobc -g` compile of the spike fixture.
LOCAL_HEADER_TEXT = """\
/* Generated by           cobc 3.2.0 */

/* LINKAGE SECTION (Items not referenced by USING clause) */
static unsigned char	*b_9 = NULL;  /* XML-NAMESPACE */
static unsigned char	*b_10 = NULL;  /* XML-NAMESPACE-PREFIX */

/* Data storage */
static int	b_2;	/* RETURN-CODE */
static cob_u8_t	b_17[10] __attribute__((aligned));	/* WS-CUSTOMER-ID */
static cob_u8_t	b_18[4] __attribute__((aligned));	/* WS-BALANCE */
static cob_u8_t	b_19[2] __attribute__((aligned));	/* WS-COUNTER */

/* End of local data storage */


/* Fields (local) */
static cob_field f_18	= {4, b_18, &a_2};	/* WS-BALANCE */
static cob_field f_19	= {2, b_19, &a_4};	/* WS-COUNTER */

/* End of fields */
"""


def test_parse_local_header_prefers_field_wrapper_over_raw_buffer():
    table = parse_local_header(LOCAL_HEADER_TEXT)

    assert table["WS-BALANCE"] == "f_18"  # f_18 comes after b_18, wins
    assert table["WS-COUNTER"] == "f_19"
    assert table["WS-CUSTOMER-ID"] == "b_17"  # no f_17 exists -- buffer only
    assert table["RETURN-CODE"] == "b_2"
    assert table["XML-NAMESPACE"] == "b_9"


class _FakeSession:
    """Maps exact MI command strings to canned records, mirroring a real
    session's responses byte-for-byte where it matters (see module
    docstring)."""

    def __init__(self, responses: dict[str, ResultRecord]):
        self._responses = responses
        self.sent: list[str] = []

    def send(self, command: str):
        self.sent.append(command)
        if command not in self._responses:
            raise AssertionError(f"unexpected MI command: {command!r}")
        return [self._responses[command]]


def _done(value=None, **extra):
    payload = dict(extra)
    if value is not None:
        payload["value"] = value
    return ResultRecord("done", payload)


def test_read_variable_decodes_packed_decimal_comp3():
    """PIC 9(5)V99 COMP-3 holding 126.45 (123.45 + three ADD 1s), read
    back as raw bytes 00 12 64 5F -- confirmed empirically."""
    session = _FakeSession(
        {
            "-data-evaluate-expression (int)(f_18).attr->type": _done("18"),
            "-data-evaluate-expression (int)(f_18).attr->digits": _done("7"),
            "-data-evaluate-expression (int)(f_18).attr->scale": _done("2"),
            "-data-evaluate-expression (int)(f_18).attr->flags": _done("0"),
            "-data-evaluate-expression (f_18).size": _done("4"),
            "-data-evaluate-expression (long)(f_18).data": _done("94006575665424"),
            "-data-evaluate-expression f_18": _done(
                '{size = 4, data = 0x5389c8c9110 <b_18> "", attr = 0x5389c8c7020 <a_2>}'
            ),
            "-data-read-memory-bytes 94006575665424 4": _done(
                memory=[{"begin": "0x0", "contents": "0012645f"}]
            ),
        }
    )

    value = read_variable(session, "WS-BALANCE", "f_18")

    assert value.kind == "packed-decimal"
    assert value.decoded == "00126.45"


def test_read_variable_decodes_binary_comp():
    """PIC S9(4) COMP holding 4, read back as raw bytes 00 04
    (big-endian) -- confirmed empirically."""
    session = _FakeSession(
        {
            "-data-evaluate-expression (int)(f_19).attr->type": _done("17"),
            "-data-evaluate-expression (int)(f_19).attr->digits": _done("4"),
            "-data-evaluate-expression (int)(f_19).attr->scale": _done("0"),
            "-data-evaluate-expression (int)(f_19).attr->flags": _done("2081"),
            "-data-evaluate-expression (f_19).size": _done("2"),
            "-data-evaluate-expression (long)(f_19).data": _done("93937745629440"),
            "-data-evaluate-expression f_19": _done(
                '{size = 2, data = 0x5389c8c9100 <b_19> "", attr = 0x5389c8c7040 <a_4>}'
            ),
            "-data-read-memory-bytes 93937745629440 2": _done(
                memory=[{"begin": "0x0", "contents": "0004"}]
            ),
        }
    )

    value = read_variable(session, "WS-COUNTER", "f_19")

    assert value.kind == "binary"
    assert value.decoded == "4"


def test_read_variable_falls_back_to_unquoted_buffer_for_plain_display_items():
    """A plain PIC X item with no runtime PICTURE decoding needs gets only
    a raw b_NN buffer, never an f_NN wrapper -- .attr access errors, and
    gdb's own quoted char-array printing is unquoted directly."""

    class _ErroringThenValueSession:
        def __init__(self):
            self.sent: list[str] = []

        def send(self, command: str):
            self.sent.append(command)
            if command == "-data-evaluate-expression (int)(b_17).attr->type":
                return [
                    ResultRecord("error", {"msg": "There is no member named attr."})
                ]
            if command == "-data-evaluate-expression b_17":
                return [_done('"CUST00001 "')]
            raise AssertionError(f"unexpected MI command: {command!r}")

    session = _ErroringThenValueSession()

    value = read_variable(session, "WS-CUSTOMER-ID", "b_17")

    assert value.kind == "alphanumeric"
    assert value.decoded == "CUST00001 "


def test_unquoted_buffer_decodes_gdbs_octal_byte_escapes():
    """Audit finding F15: gdb encodes an arbitrary non-printable byte as
    \\NNN (octal), not a named escape -- exactly the kind of value someone
    debugging a data bug (an uninitialized or garbage alphanumeric field)
    would be inspecting. \\001 must decode to the single control byte
    it represents, not the three literal characters "001"."""

    class _ErroringThenValueSession:
        def __init__(self):
            self.sent: list[str] = []

        def send(self, command: str):
            self.sent.append(command)
            if command == "-data-evaluate-expression (int)(b_17).attr->type":
                return [
                    ResultRecord("error", {"msg": "There is no member named attr."})
                ]
            if command == "-data-evaluate-expression b_17":
                # A garbage byte (0x01) followed by ordinary text -- gdb's
                # own quoted-string printing of a raw char buffer.
                return [_done('"\\001ABC"')]
            raise AssertionError(f"unexpected MI command: {command!r}")

    value = read_variable(_ErroringThenValueSession(), "WS-CUSTOMER-ID", "b_17")

    assert value.kind == "alphanumeric"
    assert value.decoded == "\x01ABC"


# --- Round-6 decoding fixes. Byte images and attr flags below are from a
# real GnuCOBOL 3.2 `cobc -std=mvs` compile in the toolchain image (see
# the decoder docstrings); the fake session only replays them.


def _field_session(expr, type_code, digits, scale, flags, hex_bytes):
    size = len(hex_bytes) // 2
    return _FakeSession(
        {
            f"-data-evaluate-expression (int)({expr}).attr->type": _done(
                str(type_code)
            ),
            f"-data-evaluate-expression (int)({expr}).attr->digits": _done(str(digits)),
            f"-data-evaluate-expression (int)({expr}).attr->scale": _done(str(scale)),
            f"-data-evaluate-expression (int)({expr}).attr->flags": _done(str(flags)),
            f"-data-evaluate-expression ({expr}).size": _done(str(size)),
            f"-data-evaluate-expression (long)({expr}).data": _done("4096"),
            f"-data-evaluate-expression {expr}": _done("{...}"),
            f"-data-read-memory-bytes 4096 {size}": _done(
                memory=[{"begin": "0x1000", "contents": hex_bytes}]
            ),
        }
    )


def test_read_variable_packed_decimal_with_even_digit_count_skips_pad_nibble():
    """PIC S9(4) COMP-3 VALUE 1234 is 01 23 4C: the pad nibble is at the
    front. Reading the first four nibbles showed 0123."""
    session = _field_session("f_17", 0x12, 4, 0, 0x0001, "01234c")

    assert read_variable(session, "WS-P4", "f_17").decoded == "1234"


def test_read_variable_packed_decimal_negative_even_digits():
    session = _field_session("f_17", 0x12, 4, 2, 0x0001, "01234d")

    assert read_variable(session, "WS-P4", "f_17").decoded == "-12.34"


def test_read_variable_signed_display_overpunch_keeps_digit_and_sign():
    """PIC S9(3)V9 VALUE -12.3 is stored `012s` (0x73 = '3' + 0x40).
    Keeping only 0-9 bytes read it as 01.2."""
    session = _field_session("f_22", 0x10, 4, 1, 0x0001, "30313273")

    value = read_variable(session, "WS-N", "f_22")

    assert value.kind == "numeric-display"
    assert value.decoded == "-012.3"


def test_read_variable_signed_display_positive_and_separate_leading():
    positive = _field_session("f_1", 0x10, 3, 0, 0x0001, "313233")
    assert read_variable(positive, "WS-P", "f_1").decoded == "123"

    # SIGN LEADING SEPARATE: HAVE_SIGN | SIGN_SEPARATE | SIGN_LEADING
    separate = _field_session("f_2", 0x10, 3, 0, 0x0007, "2d303435")
    assert read_variable(separate, "WS-L", "f_2").decoded == "-045"


def test_read_variable_comp5_is_host_order_not_big_endian():
    """PIC S9(4) COMP-5 VALUE -2: flags 0x0041 (no BINARY_SWAP), bytes
    FE FF. Big-endian decoding read -257."""
    session = _field_session("f_20", 0x11, 4, 0, 0x0041, "feff")

    assert read_variable(session, "WS-C5", "f_20").decoded == "-2"


def test_read_variable_comp_with_binary_swap_stays_big_endian():
    session = _field_session("f_19", 0x11, 4, 0, 0x0021, "fffe")

    assert read_variable(session, "WS-C", "f_19").decoded == "-2"


def test_unavailable_names_are_declared_items_missing_from_the_table():
    """Issue #156: cobc gives an item no C local when nothing generates
    code against it, so the debugger has to name it rather than drop it."""
    table = {"WS-USED": "f_8", "ws-grp": "b_10"}
    declared = ["WS-USED", "WS-UNUSED", "WS-GRP", "WS-A", "WS-UNUSED"]
    assert unavailable_names(declared, table) == ["WS-UNUSED", "WS-A"]


def test_declared_data_names_skip_filler_and_condition_names():
    from cobolparser import parse_cobol

    result = parse_cobol(
        "       IDENTIFICATION DIVISION.\n"
        "       PROGRAM-ID. DECL.\n"
        "       DATA DIVISION.\n"
        "       WORKING-STORAGE SECTION.\n"
        "       01  WS-GRP.\n"
        "           05  WS-A    PIC X.\n"
        "               88  WS-A-ON VALUE 'Y'.\n"
        "           05  FILLER  PIC X.\n"
        "       01  WS-B        PIC 9.\n"
        "       PROCEDURE DIVISION.\n"
        "           STOP RUN.\n",
        filename="decl.cbl",
    )
    assert declared_data_names(result.ast) == ["WS-GRP", "WS-A", "WS-B"]
