# Verbatim from a real `cobc -g` compile of the spike fixture.
LOCAL_HEADER_TEXT = """\
/* Generated by           cobc 3.2.0 */

/* LINKAGE SECTION (Items not referenced by USING clause) */
static unsigned char	*b_9 = NULL;  /* XML-NAMESPACE */
static unsigned char	*b_10 = NULL;  /* XML-NAMESPACE-PREFIX */

/* Data storage */
static int	b_2;	/* RETURN-CODE */
static cob_u8_t	b_17[10] __attribute__((aligned));	/* WS-CUSTOMER-ID */
static cob_u8_t	b_18[4] __attribute__((aligned));	/* WS-BALANCE */
static cob_u8_t	b_19[2] __attribute__((aligned));	/* WS-COUNTER */

/* End of local data storage */


/* Fields (local) */
static cob_field f_18	= {4, b_18, &a_2};	/* WS-BALANCE */
static cob_field f_19	= {2, b_19, &a_4};	/* WS-COUNTER */

/* End of fields */
"""


def test_parse_local_header_prefers_field_wrapper_over_raw_buffer():
    table = parse_local_header(LOCAL_HEADER_TEXT)

    assert table["WS-BALANCE"] == "f_18"  # f_18 comes after b_18, wins
    assert table["WS-COUNTER"] == "f_19"
    assert table["WS-CUSTOMER-ID"] == "b_17"  # no f_17 exists -- buffer only
    assert table["RETURN-CODE"] == "b_2"
    assert table["XML-NAMESPACE"] == "b_9"


class _FakeSession:
    """Maps exact MI command strings to canned records, mirroring a real
    session's responses byte-for-byte where it matters (see module
    docstring)."""

    def __init__(self, responses: dict[str, ResultRecord]):
        self._responses = responses
        self.sent: list[str] = []

    def send(self, command: str):
        self.sent.append(command)
        if command not in self._responses:
            raise AssertionError(f"unexpected MI command: {command!r}")
        return [self._responses[command]]


def _done(value=None, **extra):
    payload = dict(extra)
    if value is not None:
        payload["value"] = value
    return ResultRecord("done", payload)


def test_read_variable_decodes_packed_decimal_comp3():
    """PIC 9(5)V99 COMP-3 holding 126.45 (123.45 + three ADD 1s), read
    back as raw bytes 00 12 64 5F -- confirmed empirically."""
    session = _FakeSession(
        {
            "-data-evaluate-expression (int)(f_18).attr->type": _done("18"),
            "-data-evaluate-expression (int)(f_18).attr->digits": _done("7"),
            "-data-evaluate-expression (int)(f_18).attr->scale": _done("2"),
            "-data-evaluate-expression (int)(f_18).attr->flags": _done("0"),
            "-data-evaluate-expression (f_18).size": _done("4"),
            "-data-evaluate-expression (long)(f_18).data": _done("94006575665424"),
            "-data-evaluate-expression f_18": _done(
                '{size = 4, data = 0x5389c8c9110 <b_18> "", attr = 0x5389c8c7020 <a_2>}'
            ),
            "-data-read-memory-bytes 94006575665424 4": _done(
                memory=[{"begin": "0x0", "contents": "0012645f"}]
            ),
        }
    )

    value = read_variable(session, "WS-BALANCE", "f_18")

    assert value.kind == "packed-decimal"
    assert value.decoded == "00126.45"


